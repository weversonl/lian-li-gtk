//! All user-visible text, in English and Brazilian Portuguese, keyed by a
//! short string ID. Centralized in one file (rather than scattering
//! `if lang == ... { "..." } else { "..." }` at each call site) so both
//! languages for a given string sit right next to each other — easy to
//! audit for a missing translation, and there's exactly one place to add a
//! new string. Call sites use `t(lang, "key")` (or `ctx.t("key")`, which
//! reads the current language for you).
//!
//! Keys are grouped by the page/module that uses them. A key that's shared
//! across pages (e.g. "Save") is deliberately duplicated per call site
//! rather than factored into one shared key — two unrelated buttons that
//! happen to say the same thing in English aren't guaranteed to stay the
//! same thing forever, and a shared key would couple them.

